#!/bin/bash

if [ "$HARDWARE_MODE" == "2" ]; then

	TOTAL_THREADS_AVAILABLE=$1
	THREADS_FOR_GPU_PROCESSES=1
	THREADS_FOR_CPU_PROCESS=$(( TOTAL_THREADS_AVAILABLE - THREADS_FOR_GPU_PROCESSES * (LOCAL_WORLD_SIZE - 1) ))

	echo "Total Threads: $TOTAL_THREADS_AVAILABLE, threads for cpu process: $THREADS_FOR_CPU_PROCESS"

	if [ "$THREADS_FOR_CPU_PROCESS" -le "0" ]; then
		if [ "$LOCAL_RANK" -eq "0" ]; then
			echo "Not enough threads left to run the cpu process. Re-run in GPU-only mode or decrease the number of GPUs to run along with this CPU."
		fi 
	      exit 1
	fi

	if [ "$LOCAL_RANK" -eq "0" ]; then
		echo "TOTAL THREADS ON THIS NODE: $TOTAL_THREADS_AVAILABLE, PROCESSES LAUNCHED: $LOCAL_WORLD_SIZE, THREADS FOR CPU PROCESS: $THREADS_FOR_CPU_PROCESS, NUMBER OF CPU PROCESSES: 1, NUMBER OF GPU PROCESSES: $(( LOCAL_WORLD_SIZE-1 ))"
		export OMP_NUM_THREADS=$THREADS_FOR_CPU_PROCESS
		export MKL_NUM_THREADS=$THREADS_FOR_CPU_PROCESS
		export OPENBLAS_NUM_THREADS=$THREADS_FOR_CPU_PROCESS
	else
		export OMP_NUM_THREADS=$THREADS_FOR_GPU_PROCESSES
		export MKL_NUM_THREADS=$THREADS_FOR_GPU_PROCESSES
		export OPENBLAS_NUM_THREADS=$THREADS_FOR_GPU_PROCESSES
	fi

fi

exec python -u XSENSE/XSENSE.py
